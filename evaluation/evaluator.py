"""
Main RAG evaluator — orchestrates TRACe and traditional metrics,
produces per-example and aggregate results for one or more RAG models.
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Optional

from tqdm import tqdm

from .trace_metrics import TRACeEvaluator, TRACeScores
from .traditional_metrics import TraditionalMetrics, TraditionalScores


@dataclass
class ExampleResult:
    """Full evaluation output for a single example."""
    example_id: int
    subset: str
    domain: str
    question: str
    trace: TRACeScores
    traditional: TraditionalScores


@dataclass
class ModelEvaluation:
    """Aggregate evaluation for one RAG model across a dataset."""
    model_name: str
    per_example: list[ExampleResult] = field(default_factory=list)
    trace_aggregate: dict = field(default_factory=dict)
    traditional_aggregate: dict = field(default_factory=dict)
    per_subset_trace: dict = field(default_factory=dict)
    per_domain_trace: dict = field(default_factory=dict)


class RAGEvaluator:
    """
    Central evaluation engine.

    Workflow:
      1. Feed examples (loaded from RAGBench, or generated by a RAG model).
      2. Optionally provide model-generated responses to override the default.
      3. Compute TRACe + traditional metrics.
      4. Aggregate across the whole dataset, per-subset, per-domain.
    """

    def __init__(
        self,
        compute_bertscore: bool = False,
        fuzzy_threshold: float = 0.6,
    ):
        self.trace_eval = TRACeEvaluator(fuzzy_threshold=fuzzy_threshold)
        self.trad_eval = TraditionalMetrics(compute_bertscore=compute_bertscore)

    def evaluate(
        self,
        examples: list[dict],
        model_name: str = "default",
        model_responses: list[str] | None = None,
        use_ground_truth_trace: bool = True,
    ) -> ModelEvaluation:
        """
        Run full evaluation.

        Parameters
        ----------
        examples : normalised RAGBench examples (from data_loader).
        model_name : identifier for the RAG model being evaluated.
        model_responses : if provided, overrides `example["response"]`.
        use_ground_truth_trace : use annotated TRACe labels if available.
        """
        if model_responses is not None and len(model_responses) != len(examples):
            raise ValueError("model_responses length must match examples length")

        per_example: list[ExampleResult] = []

        predictions: list[str] = []
        references: list[str] = []

        for i, ex in enumerate(tqdm(examples, desc=f"Evaluating [{model_name}]")):
            response = model_responses[i] if model_responses else ex["response"]

            # TRACe
            if use_ground_truth_trace and ex.get("relevance") is not None:
                trace_scores = self.trace_eval.scores_from_ground_truth(ex)
            else:
                trace_scores = self.trace_eval.estimate_scores(
                    question=ex["question"],
                    response=response,
                    documents=ex["documents"],
                )

            predictions.append(response)
            references.append(ex.get("ground_truth_response") or "")

            per_example.append(ExampleResult(
                example_id=i,
                subset=ex["subset"],
                domain=ex["domain"],
                question=ex["question"],
                trace=trace_scores,
                traditional=TraditionalScores(),  # filled after batch BERTScore
            ))

        # Traditional metrics (batch for BERTScore efficiency)
        trad_scores = self.trad_eval.score_batch(predictions, references)
        for er, ts in zip(per_example, trad_scores):
            er.traditional = ts

        # Aggregate
        all_trace = [er.trace for er in per_example]
        all_trad = [er.traditional for er in per_example]

        trace_agg = TRACeEvaluator.aggregate(all_trace)
        trad_agg = TraditionalMetrics.aggregate(all_trad)

        # Per-subset and per-domain aggregation for TRACe
        per_subset_trace = self._group_aggregate(per_example, key="subset")
        per_domain_trace = self._group_aggregate(per_example, key="domain")

        return ModelEvaluation(
            model_name=model_name,
            per_example=per_example,
            trace_aggregate=trace_agg,
            traditional_aggregate=trad_agg,
            per_subset_trace=per_subset_trace,
            per_domain_trace=per_domain_trace,
        )

    def _group_aggregate(self, results: list[ExampleResult], key: str) -> dict:
        groups: dict[str, list[TRACeScores]] = {}
        for er in results:
            g = getattr(er, key)
            groups.setdefault(g, []).append(er.trace)
        return {g: TRACeEvaluator.aggregate(scores) for g, scores in groups.items()}
